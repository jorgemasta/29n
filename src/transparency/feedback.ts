// "Reportar error" and "Falta un partido" without a GitHub account (#11, built with #15): the
// Cloudflare function POST /api/avisar files the public issue with the project's token. Without a
// token (or if GitHub fails) the page falls back to the prefilled GitHub link, as before.
//
//   createFeedback({ createIssue?, store? }).send(request, session) → created | unavailable | invalid | limit | error
//
// Same no-logs policy as the free question: only what the voter typed in the form becomes the
// (public) issue; the session id is only kept hashed, as a counter that expires. No IP is received.
import { z } from 'zod';
import { sha256, type Store } from '../questions/free';
import { missingPartyIssue, reportErrorIssue, MAX_COMMENT, REPORT_REASONS, missingPartyUrl, reportErrorUrl, type IssueContent } from './index';

/** Notices per session and day. */
export const FEEDBACK_LIMIT = 5;
/** Notices per day across everyone: the session id is generated by the browser, so a new one per
 * request skips the per-session limit; this cap bounds what can reach the public repo. */
export const DAILY_FEEDBACK_LIMIT = 30;
const SESSION_TTL = 24 * 3600;

const text = (max: number) => z.string().trim().max(max);
const safeLink = z
  .string()
  .trim()
  .max(300)
  .refine((u) => u === '' || /^https:\/\/[^\s]+$/.test(u), 'enlace no válido');

export const FeedbackRequest = z.discriminatedUnion('type', [
  z.object({
    type: z.literal('report-error'),
    topic: z.object({ id: text(80).min(1), title: text(150).min(1) }),
    party: z.object({ id: text(80).min(1), name: text(150).min(1) }),
    letter: z.string().regex(/^[A-Z]$/),
    pages: z.array(z.number().int().min(1).max(5000)).max(20),
    reason: z.enum(REPORT_REASONS.map((m) => m.id) as [string, ...string[]]),
    comment: z.string().max(MAX_COMMENT).optional(),
  }),
  z.object({
    type: z.literal('missing-party'),
    party: text(150).min(1),
    provinces: text(300).optional(),
    reason: text(1000).optional(),
    link: safeLink.optional(),
  }),
]);
export type FeedbackRequest = z.infer<typeof FeedbackRequest>;

export type FeedbackResult =
  | { state: 'created'; url: string }
  | { state: 'unavailable'; fallbackUrl: string }
  | { state: 'invalid'; message: string }
  | { state: 'limit'; message: string; fallbackUrl: string }
  | { state: 'error'; message: string; fallbackUrl: string };

export interface FeedbackPorts {
  /** Files a public issue; absent when no token is configured. */
  createIssue?: (issue: { title: string; body: string; labels: string[] }) => Promise<{ url: string }>;
  store?: Store;
  now?: () => Date;
}

/** "@usuario" would notify a GitHub user: break the mention with a zero-width space. */
const noMentions = (t: string) => t.replace(/@(?=[\w-])/g, '@​');

export function createFeedback(ports: FeedbackPorts) {
  return {
    async send(request: unknown, session: string): Promise<FeedbackResult> {
      const p = FeedbackRequest.safeParse(request);
      if (!p.success) return { state: 'invalid', message: 'Faltan datos o no son válidos. Revisa el formulario.' };
      const d = p.data;
      const fallbackUrl = d.type === 'report-error' ? reportErrorUrl(d as Parameters<typeof reportErrorUrl>[0]) : missingPartyUrl(d);
      if (!ports.createIssue) return { state: 'unavailable', fallbackUrl };

      const sessionKey = ports.store ? `feedback:${await sha256(`29n-aviso:${session}`)}` : null;
      const used = sessionKey ? Number((await ports.store!.get(sessionKey)) ?? 0) || 0 : 0;
      if (used >= FEEDBACK_LIMIT)
        return { state: 'limit', message: `Has enviado ${FEEDBACK_LIMIT} avisos hoy. Si necesitas enviar más, puedes hacerlo en GitHub.`, fallbackUrl };
      const dayKey = ports.store ? `feedback-day:${(ports.now?.() ?? new Date()).toISOString().slice(0, 10)}` : null;
      const today = dayKey ? Number((await ports.store!.get(dayKey)) ?? 0) || 0 : 0;
      if (today >= DAILY_FEEDBACK_LIMIT)
        return { state: 'limit', message: 'Hoy ya hemos recibido muchos avisos desde la web. Puedes enviarlo en GitHub.', fallbackUrl };

      const issue: IssueContent = d.type === 'report-error' ? reportErrorIssue(d as Parameters<typeof reportErrorIssue>[0]) : missingPartyIssue(d);
      try {
        const { url } = await ports.createIssue({
          title: noMentions(issue.title),
          body: `${noMentions(issue.body)}\n\n---\n_Enviado desde la web, sin cuenta de GitHub._`,
          labels: [issue.label],
        });
        if (sessionKey) await ports.store!.put(sessionKey, String(used + 1), { expirationTtl: SESSION_TTL });
        if (dayKey) await ports.store!.put(dayKey, String(today + 1), { expirationTtl: 2 * SESSION_TTL });
        return { state: 'created', url };
      } catch {
        return { state: 'error', message: 'No hemos podido enviarlo. Puedes hacerlo en GitHub.', fallbackUrl };
      }
    },
  };
}
