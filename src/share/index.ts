/**
 * How a line is drawn. 'huge' is the big number; its next line continues the same sentence
 * (the alt text joins them with a space). 'lead' is the card's main sentence.
 */
export type Style = 'header' | 'huge' | 'lead' | 'normal' | 'label' | 'highlight' | 'closing' | 'web' | 'footer' | 'warning';

export interface Line {
  text: string;
  style: Style;
}

export interface Bar {
  text: string;
  percent: number;
}

export interface CardContent {
  variant: Variant;
  /** Lines from top to bottom; in the ranking variant the bars go right after the first line. */
  lines: Line[];
  /** Top 3 of the ranking, one tone. Always empty in the default variant. */
  bars: Bar[];
}

/** Themes named on the default card; beyond this they are counted ("5 temáticas"). */
const MAX_NAMED_THEMES = 3;

const questionsIn = (a: Affinity) => a.themes.reduce((s, t) => s + t.questions, 0);
const noneIn = (a: Affinity) => a.themes.reduce((s, t) => s + t.none, 0);

/** Different parties that coincided with the voter in at least one revealed theme. */
function distinctParties(a: Affinity): number {
  return new Set(a.themes.flatMap((t) => t.rows.filter((r) => r.points > 0).map((r) => r.party.id))).size;
}

/** The default card needs one revealed theme; the ranking, an overall ranking where someone coincided. */
export function variantAvailable(a: Affinity, v: Variant): boolean {
  if (!a.themes.length) return false;
  return v === 'no-parties' || (a.ranking?.some((r) => r.points > 0) ?? false);
}

export function cardContent(a: Affinity, variant: Variant): CardContent {
  return variant === 'ranking' && variantAvailable(a, 'ranking') ? withRanking(a) : noParties(a);
}

function noParties(a: Affinity): CardContent {
  const titles = a.themes.map((t) => t.theme.title);
  const played = titles.length > MAX_NAMED_THEMES ? plural(titles.length, 'temática', 'temáticas') : joinList(titles);
  const n = distinctParties(a);
  const coincided =
    n === 0 ? 'no coincidí con ningún partido' : n === 1 ? 'coincidí con 1 partido' : `coincidí con ${n} partidos distintos`;
  return {
    variant: 'no-parties',
    bars: [],
    lines: [
      { text: '29N · Elegido a ciegas', style: 'header' },
      { text: `He hecho ${played} a ciegas: ${coincided}.`, style: 'lead' },
      { text: `${plural(questionsIn(a), 'pregunta', 'preguntas')}, sin saber qué partidos había detrás de cada propuesta.`, style: 'normal' },
      { text: '¿Y tú? Lee las propuestas sin saber de quién son.', style: 'closing' },
      { text: DOMAIN, style: 'web' },
      { text: 'Sin registro · Sin datos personales · Con citas de los programas', style: 'footer' },
    ],
  };
}

function withRanking(a: Affinity): CardContent {
  const ranking = a.ranking ?? [];
  const top = ranking.slice(0, 3);
  const rest = ranking.length - top.length;
  const none = noneIn(a);
  const missing = a.missingManifestos.length;
  const lines: Line[] = [{ text: '29N · Con quién coincido a ciegas', style: 'header' }];
  if (rest > 0) lines.push({ text: `+${plural(rest, 'partido más', 'partidos más')}`, style: 'normal' });
  lines.push({
    text:
      `En ${plural(a.themes.length, 'temática', 'temáticas')}, ${plural(questionsIn(a), 'pregunta', 'preguntas')}` +
      (none ? ` · ${plural(none, 'vez', 'veces')} ninguna me convenció` : ''),
    style: 'normal',
  });
  if (missing) lines.push({ text: missing === 1 ? 'Falta 1 programa.' : `Faltan ${missing} programas.`, style: 'normal' });
  lines.push({ text: 'No es una recomendación de voto.', style: 'warning' }, { text: DOMAIN, style: 'web' });
  return {
    variant: 'ranking',
    lines,
    bars: top.map((r) => ({ text: `${r.party.name} ${r.percent} %${r.tie ? ' (empate)' : ''}`, percent: r.percent })),
  };
}

/** Alt text of the image: the same content, read top to bottom. */
export function altText(c: CardContent): string {
  const sentences: string[] = [];
  const withPeriod = (t: string) => (/[.?!]$/.test(t) ? t : `${t}.`);
  c.lines.forEach((l, i) => {
    if (i > 0 && c.lines[i - 1]!.style === 'huge') sentences[sentences.length - 1] = `${c.lines[i - 1]!.text} ${l.text}`;
    else sentences.push(l.text);
    if (i === 0) sentences.push(...c.bars.map((b) => b.text));
  });
  return ['Tarjeta de 29N', ...sentences].map(withPeriod).join(' ');
}

/** True when the page was opened from a shared link (?r=reto). */
export function isChallenge(search: string): boolean {
  return new URLSearchParams(search).get('r') === 'reto';
}

/** Line above the home headline when the visitor comes from a challenge. */
export function challengeHomeText(search: string): string | null {
  return isChallenge(search) ? 'Alguien te reta: elige a ciegas y mira con cuántos partidos coincides.' : null;
}

/** Served HTML for /?r=reto: only the og/twitter title meta tags change (used by the Worker). */
export function applyChallenge(html: string): string {
  return html.replaceAll(`content="${OG.title}"`, `content="${OG.challengeTitle}"`);
}
