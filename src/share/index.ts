/**
 * How a line is drawn. 'enorme' is the big number; its next line continues the same sentence
 * (the alt text joins them with a space).
 */
export type Style = 'header' | 'huge' | 'normal' | 'label' | 'highlight' | 'closing' | 'web' | 'footer' | 'warning';

export interface Line {
  text: string;
  style: Style;
}

export interface Bar {
  text: string;
  percent: number;
}

export interface CardContent {
  variant: Variant;
  /** Lines from top to bottom; in the ranking variant the bars go right after the first line. */
  lines: Line[];
  /** Top 3 of the ranking, one tone. Always empty in the default variant. */
  bars: Bar[];
}

const plural = (n: number, one: string, many: string) => `${n} ${n === 1 ? one : many}`;

/** First-person version of the result label ("Lo tienes claro." on screen). */
function label(n: number): string {
  return n <= 1 ? 'Lo tengo claro.' : n <= 3 ? 'Con matices.' : 'Vas por libre.';
}

export function variantAvailable(r: Result, v: Variant): boolean {
  if (!r.available) return false;
  return v === 'no-parties' || r.ranking.length > 0;
}

export function cardContent(r: Result, variant: Variant): CardContent {
  return variant === 'ranking' && r.ranking.length > 0 ? withRanking(r) : noParties(r);
}

function noParties(r: Result): CardContent {
  const tagline = 'sin saber de quién era cada propuesta.';
  const number: Line[] = r.allNone
    ? [
        { text: 'Ninguna', style: 'huge' },
        { text: `me convenció en ${r.topics} temas, ${tagline}`, style: 'normal' },
      ]
    : [
        { text: plural(r.distinctParties, 'partido', 'partidos'), style: 'huge' },
        { text: `${r.distinctParties === 1 ? '' : 'distintos '}en ${r.topics} temas, ${tagline}`, style: 'normal' },
        { text: label(r.distinctParties), style: 'label' },
      ];
  const { total, wrong } = r.guesses;
  return {
    variant: 'no-parties',
    bars: [],
    lines: [
      { text: '29N · Elegido a ciegas', style: 'header' },
      ...number,
      ...(total >= 3 ? [{ text: `${wrong} de ${total} veces no era de quien yo pensaba.`, style: 'highlight' as const }] : []),
      { text: '¿Y tú? Lee las propuestas sin saber de quién son.', style: 'closing' },
      { text: DOMAIN, style: 'web' },
      { text: 'Sin registro · Sin datos personales · Con citas de los programas', style: 'footer' },
    ],
  };
}

function withRanking(r: Result): CardContent {
  const top = r.ranking.slice(0, 3);
  const rest = r.ranking.length - top.length;
  const pending = r.pending.length;
  const lines: Line[] = [{ text: '29N · Con quién coincido a ciegas', style: 'header' }];
  if (rest > 0) lines.push({ text: `+${plural(rest, 'partido más', 'partidos más')}`, style: 'normal' });
  lines.push({
    text: `En ${r.topics} temas${r.none ? ` · ${plural(r.none, 'vez', 'veces')} ninguna me convenció` : ''}`,
    style: 'normal',
  });
  if (pending) lines.push({ text: `⏳ ${pending === 1 ? 'Falta 1 programa' : `Faltan ${pending} programas`}.`, style: 'normal' });
  lines.push({ text: 'No es una recomendación de voto.', style: 'warning' }, { text: DOMAIN, style: 'web' });
  return {
    variant: 'ranking',
    lines,
    bars: top.map((f) => ({ text: `${f.party.name} ${f.percent} %${f.tie ? ' (empate)' : ''}`, percent: f.percent })),
  };
}

/** Alt text of the image: the same content, read top to bottom. */
export function altText(c: CardContent): string {
  const sentences: string[] = [];
  const withPeriod = (t: string) => (/[.?!]$/.test(t) ? t : `${t}.`);
  c.lines.forEach((l, i) => {
    if (i > 0 && c.lines[i - 1]!.style === 'huge') sentences[sentences.length - 1] = `${c.lines[i - 1]!.text} ${l.text}`;
    else sentences.push(l.text);
    if (i === 0) sentences.push(...c.bars.map((b) => b.text));
  });
  return ['Tarjeta de 29N', ...sentences].map(withPeriod).join(' ');
}

/** True when the page was opened from a shared link (?r=reto). */
export function isChallenge(search: string): boolean {
  return new URLSearchParams(search).get('r') === 'reto';
}

/** Line above the home headline when the visitor comes from a challenge. */
export function challengeHomeText(search: string): string | null {
  return isChallenge(search) ? 'Alguien te reta: ¿con quién coincides sin saberlo?' : null;
}

/** Served HTML for /?r=reto: only the og/twitter title meta tags change (used by the Worker). */
export function applyChallenge(html: string): string {
  return html.replaceAll(`content="${OG.title}"`, `content="${OG.challengeTitle}"`);
}
