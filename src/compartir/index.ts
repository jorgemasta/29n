/**
 * How a line is drawn. 'enorme' is the big number; its next line continues the same sentence
 * (the alt text joins them with a space).
 */
export type Estilo = 'cabecera' | 'enorme' | 'normal' | 'etiqueta' | 'destacado' | 'cierre' | 'web' | 'pie' | 'aviso';

export interface Linea {
  texto: string;
  estilo: Estilo;
}

export interface Barra {
  texto: string;
  porcentaje: number;
}

export interface ContenidoTarjeta {
  variante: Variante;
  /** Lines from top to bottom; in the ranking variant the bars go right after the first line. */
  lineas: Linea[];
  /** Top 3 of the ranking, one tone. Always empty in the default variant. */
  barras: Barra[];
}

const plural = (n: number, uno: string, varios: string) => `${n} ${n === 1 ? uno : varios}`;

/** First-person version of the result label ("Lo tienes claro." on screen). */
function etiqueta(n: number): string {
  return n <= 1 ? 'Lo tengo claro.' : n <= 3 ? 'Con matices.' : 'Vas por libre.';
}

export function varianteDisponible(r: Resultado, v: Variante): boolean {
  if (!r.disponible) return false;
  return v === 'sin-partidos' || r.ranking.length > 0;
}

export function contenidoTarjeta(r: Resultado, variante: Variante): ContenidoTarjeta {
  return variante === 'ranking' && r.ranking.length > 0 ? conRanking(r) : sinPartidos(r);
}

function sinPartidos(r: Resultado): ContenidoTarjeta {
  const coletilla = 'sin saber de quién era cada propuesta.';
  const numero: Linea[] = r.todoNinguna
    ? [
        { texto: 'Ninguna', estilo: 'enorme' },
        { texto: `me convenció en ${r.temas} temas, ${coletilla}`, estilo: 'normal' },
      ]
    : [
        { texto: plural(r.partidosDistintos, 'partido', 'partidos'), estilo: 'enorme' },
        { texto: `${r.partidosDistintos === 1 ? '' : 'distintos '}en ${r.temas} temas, ${coletilla}`, estilo: 'normal' },
        { texto: etiqueta(r.partidosDistintos), estilo: 'etiqueta' },
      ];
  const { total, falladas } = r.apuestas;
  return {
    variante: 'sin-partidos',
    barras: [],
    lineas: [
      { texto: '29N · Elegido a ciegas', estilo: 'cabecera' },
      ...numero,
      ...(total >= 3 ? [{ texto: `${falladas} de ${total} veces no era de quien yo pensaba.`, estilo: 'destacado' as const }] : []),
      { texto: '¿Y tú? Lee las propuestas sin saber de quién son.', estilo: 'cierre' },
      { texto: DOMINIO, estilo: 'web' },
      { texto: 'Sin registro · Sin datos personales · Con citas de los programas', estilo: 'pie' },
    ],
  };
}

function conRanking(r: Resultado): ContenidoTarjeta {
  const primeros = r.ranking.slice(0, 3);
  const resto = r.ranking.length - primeros.length;
  const pendientes = r.pendientes.length;
  const lineas: Linea[] = [{ texto: '29N · Con quién coincido a ciegas', estilo: 'cabecera' }];
  if (resto > 0) lineas.push({ texto: `+${plural(resto, 'partido más', 'partidos más')}`, estilo: 'normal' });
  lineas.push({
    texto: `En ${r.temas} temas${r.ninguna ? ` · ${plural(r.ninguna, 'vez', 'veces')} ninguna me convenció` : ''}`,
    estilo: 'normal',
  });
  if (pendientes) lineas.push({ texto: `⏳ ${pendientes === 1 ? 'Falta 1 programa' : `Faltan ${pendientes} programas`}.`, estilo: 'normal' });
  lineas.push({ texto: 'No es una recomendación de voto.', estilo: 'aviso' }, { texto: DOMINIO, estilo: 'web' });
  return {
    variante: 'ranking',
    lineas,
    barras: primeros.map((f) => ({ texto: `${f.partido.nombre} ${f.porcentaje} %${f.empate ? ' (empate)' : ''}`, porcentaje: f.porcentaje })),
  };
}

/** Alt text of the image: the same content, read top to bottom. */
export function textoAlternativo(c: ContenidoTarjeta): string {
  const frases: string[] = [];
  const conPunto = (t: string) => (/[.?!]$/.test(t) ? t : `${t}.`);
  c.lineas.forEach((l, i) => {
    if (i > 0 && c.lineas[i - 1]!.estilo === 'enorme') frases[frases.length - 1] = `${c.lineas[i - 1]!.texto} ${l.texto}`;
    else frases.push(l.texto);
    if (i === 0) frases.push(...c.barras.map((b) => b.texto));
  });
  return ['Tarjeta de 29N', ...frases].map(conPunto).join(' ');
}

/** True when the page was opened from a shared link (?r=reto). */
export function esReto(search: string): boolean {
  return new URLSearchParams(search).get('r') === 'reto';
}

/** Line above the home headline when the visitor comes from a challenge. */
export function textoPortadaReto(search: string): string | null {
  return esReto(search) ? 'Alguien te reta: ¿con quién coincides sin saberlo?' : null;
}

/** Served HTML for /?r=reto: only the og/twitter title meta tags change (used by the Worker). */
export function aplicarReto(html: string): string {
  return html.replaceAll(`content="${OG.titulo}"`, `content="${OG.tituloReto}"`);
}
